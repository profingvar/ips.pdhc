-- #891 (EPS C4): patient_clinic_assignments records when an assignment began
-- and never that it ended.
--
-- ips.pdhc creates schema via db.create_all(), which adds missing TABLES only
-- and never alters an existing one, so a new column needs an explicit ALTER on
-- prod. Idempotent, same pattern as add_patient_archived_at.sql (#811) and
-- add_reform_patient_flags.sql (#404).
--
-- Why this matters beyond tidiness: GET /api/v1/clinics/<guid>/patients reads
-- this table and sim.pdhc builds cohorts from it. Without an end date a
-- patient who moved clinic is either still assigned to the old one or has no
-- record of ever having been -- and deleting the row loses the second fact to
-- fix the first.
--
-- Why a NEW column and not `expires_at`, which exists on patient_block,
-- patient_consent, emergency_access and api_key: those are EXPIRIES, a planned
-- future end set when the row is created. This is an end that HAPPENED, set
-- when it happens. They are not interchangeable -- an expiry in the future
-- means "still valid", while a non-NULL ended_at always means "over".
--
-- NULLABLE with no default, so every existing row stays NULL = still active
-- and no consumer's current answer changes. Eleven sibling services read this
-- table set, so changes here are additive by rule.
--
-- Run on miserver:
--   docker exec -i ips-db-1 psql -U ips_user -d ips_db -f - \
--       < add_assignment_ended_at.sql

ALTER TABLE patient_clinic_assignments
    ADD COLUMN IF NOT EXISTS ended_at TIMESTAMPTZ;

-- THE UNIQUE RULE HAS TO CHANGE, or the column means less than it looks.
--
-- The old UniqueConstraint(patient_guid, clinic_guid) made "ended" a TERMINAL
-- state per pair: a patient returning to a clinic they had left could not be
-- re-assigned, because the closed row still occupied the pair. The replacement
-- is a PARTIAL unique index over OPEN assignments only -- at most one active
-- assignment per (patient, clinic), any number of closed ones.
--
-- For every row that exists when this runs (all ended_at IS NULL) the two
-- rules are identical, so nothing currently stored is affected and nothing can
-- fail to migrate.
--
-- ORDER MATTERS: the new index is created BEFORE the old constraint is
-- dropped, so there is never a moment with no uniqueness on this table.
CREATE UNIQUE INDEX IF NOT EXISTS uq_patient_clinic_active
    ON patient_clinic_assignments (patient_guid, clinic_guid)
    WHERE ended_at IS NULL;

-- The old constraint's name was generated by Postgres, so it is LOOKED UP by
-- the columns it covers rather than hardcoded. Hardcoding
-- `patient_clinic_assignments_patient_guid_clinic_guid_key` would silently do
-- nothing on a database where it was named differently -- and "silently did
-- nothing" is indistinguishable from success in a migration.
DO $$
DECLARE
    con_name text;
BEGIN
    SELECT c.conname INTO con_name
      FROM pg_constraint c
      JOIN pg_class t ON t.oid = c.conrelid
     WHERE t.relname = 'patient_clinic_assignments'
       AND c.contype = 'u'
       AND (
            SELECT array_agg(a.attname::text ORDER BY a.attname)
              FROM unnest(c.conkey) k
              JOIN pg_attribute a
                ON a.attrelid = c.conrelid AND a.attnum = k
           ) = ARRAY['clinic_guid', 'patient_guid']
     LIMIT 1;

    IF con_name IS NULL THEN
        RAISE NOTICE 'no (patient_guid, clinic_guid) unique constraint found — already migrated';
    ELSE
        EXECUTE format('ALTER TABLE patient_clinic_assignments DROP CONSTRAINT %I',
                       con_name);
        RAISE NOTICE 'dropped unique constraint %', con_name;
    END IF;
END $$;
